// Generated by the test runner: get_out_diff and forward_with_lora are copied
// verbatim from the actual selected source. Only metadata fixtures surround them.
#include "exact-lora-methods.hpp"

static void put_pair(MetadataLora& lora, ggml_context* params, const std::string& weight,
                     int64_t in_features, int64_t out_features) {
    const std::string down = "lora." + weight + ".lora_down";
    const std::string up = "lora." + weight + ".lora_up";
    auto* a = ggml_new_tensor_2d(params, GGML_TYPE_F32, in_features, 16);
    auto* b = ggml_new_tensor_2d(params, GGML_TYPE_F32, 16, out_features);
    ggml_set_name(a, down.c_str()); ggml_set_name(b, up.c_str());
    check(lora.lora_tensors.emplace(down, a).second, "unique LoRA down metadata");
    check(lora.lora_tensors.emplace(up, b).second, "unique LoRA up metadata");
}

int main(int argc, char** argv) {
    check(argc == 2, "selected header-only fixture argument");
    std::ifstream input(argv[1]); nlohmann::json metadata; input >> metadata;
    check(metadata.at("payload_bytes_read") == 0 && metadata.at("tensors").size() == 379,
          "actual379 header-only tensors without weight values");
    const std::string prefix = "model.diffusion_model";
    String2TensorStorage weights;
    for (const auto& row : metadata.at("tensors")) {
        TensorStorage s; s.name = prefix + "." + row.at("name").get<std::string>();
        s.type = static_cast<ggml_type>(row.at("type_id").get<int>());
        s.n_dims = static_cast<int>(row.at("shape").size());
        for (int i = 0; i < s.n_dims; ++i) s.ne[i] = row.at("shape").at(i).get<int64_t>();
        weights.emplace(s.name, s);
    }
    auto config = MOSSImage::MOSSImageConfig::detect_from_weights(weights, prefix);
    check(config.depth == 42 && config.dim == 3072 && config.channels == 128 && config.ffn_dim == 8192,
          "selected actual42-layer MOSS dimensions");
    constexpr auto expected = PS5_AI_MOSS_F32_ACCUMULATION ? GGML_PREC_F32 : GGML_PREC_DEFAULT;
    nlohmann::json cases = nlohmann::json::array();
    std::map<std::string, int> parameter_dtypes;
    for (bool lora_enabled : {false, true}) {
        for (int latent_side : {16, 64}) {
            for (bool skip_one_layer : {false, true}) {
                auto* params = ggml_init({32 << 20, nullptr, true});
                auto* context = ggml_init({128 << 20, nullptr, true});
                check(params && context, "no-alloc metadata contexts");
                {
                    MOSSImage::Model model(config); model.init(params, weights, prefix);
                    std::map<std::string, ggml_tensor*> actual; model.get_param_tensors(actual, prefix);
                    check(actual.size() == 378, "all model parameters created");
                    std::map<std::string, int> case_dtypes;
                    for (const auto& [name, tensor] : actual) {
                        check(weights.count(name) == 1, "all parameters correspond to selected source metadata");
                        case_dtypes.emplace(name, int(tensor->type));
                        check(tensor->data == nullptr, "model tensor payload not allocated");
                    }
                    // Bias/norm creation already uses F32 regardless of source
                    // storage dtype. Compare the complete CREATED mapping across
                    // flag0/1 instead of claiming all storage dtypes are native.
                    if (parameter_dtypes.empty()) parameter_dtypes = case_dtypes;
                    check(case_dtypes == parameter_dtypes, "created parameter dtype mapping stable across all graphs");
                    GGMLRunnerContext runner; runner.backend = reinterpret_cast<ggml_backend_t>(uintptr_t(1));
                    runner.ggml_ctx = context; runner.flash_attn_enabled = true;
                    auto lora = std::make_shared<MetadataLora>();
                    if (lora_enabled) {
                        for (int layer = 0; layer < 42; ++layer) {
                            const auto base = prefix + ".layers." + std::to_string(layer) + ".proj.";
                            for (int split = 0; split < 3; ++split)
                                put_pair(*lora, params, base + "qkv.weight" + (split ? "." + std::to_string(split) : ""), 3072, 3072);
                            put_pair(*lora, params, base + "o.weight", 3072, 3072);
                            put_pair(*lora, params, base + "ffn_up_gate.weight", 3072, 16384);
                            put_pair(*lora, params, base + "ffn_down.weight", 8192, 3072);
                        }
                        check(lora->lora_tensors.size() == 504, "requested normal504-tensor rank16 LoRA metadata schema");
                        runner.weight_adapter = std::make_shared<MetadataAdapter>(std::vector{lora});
                    }
                    const int tokens = skip_one_layer ? 45 : 48;
                    auto* image = ggml_new_tensor_4d(context, GGML_TYPE_F32, latent_side, latent_side, 128, 1);
                    auto* time = ggml_new_tensor_3d(context, GGML_TYPE_F32, 256, 1, 1);
                    auto* text = ggml_new_tensor_3d(context, GGML_TYPE_F32, 4096, tokens, 1);
                    auto* pe = ggml_new_tensor_4d(context, GGML_TYPE_F32, 2, 2, 64, latent_side * latent_side + tokens);
                    auto* graph = ggml_new_graph_custom(context, 65536, false);
                    const std::vector<int> skip = skip_one_layer ? std::vector<int>{22} : std::vector<int>{};
                    ggml_build_forward_expand(graph, model.forward(&runner, image, time, text, pe, skip));
                    unsigned base_count = 0, lora_count = 0, quantized = 0, bf16 = 0, flash = 0;
                    for (int i = 0; i < ggml_graph_n_nodes(graph); ++i) {
                        auto* t = ggml_graph_node(graph, i);
                        check(t->data == nullptr, "graph tensor payload not allocated");
                        if (t->op == GGML_OP_FLASH_ATTN_EXT) {
                            ++flash; check(t->op_params[3] == GGML_PREC_F32, "existing MOSS FA F32 policy unchanged");
                        }
                        if (t->op != GGML_OP_MUL_MAT) continue;
                        check(t->op_params[0] == expected, "every MOSS base and LoRA MUL_MAT inherits selected accumulator policy");
                        std::string name = t->src[0]->name;
                        if (name.rfind("lora.", 0) == 0) {
                            ++lora_count; check(t->src[0]->type == GGML_TYPE_F32, "LoRA F32 payload type preserved");
                        } else {
                            ++base_count; quantized += t->src[0]->type == GGML_TYPE_Q4_K;
                            bf16 += t->src[0]->type == GGML_TYPE_BF16;
                        }
                    }
                    check(base_count == (skip_one_layer ? 181u : 185u), "all owned Linear projections inspected, including embeddings/modulation/output");
                    check(quantized == (skip_one_layer ? 164u : 168u) && bf16 == 17, "base Q4 and BF16 graph dtypes unchanged");
                    check(flash == (skip_one_layer ? 43u : 44u), "existing attention graph structure unchanged");
                    check(lora_count == (lora_enabled ? (skip_one_layer ? 492u : 504u) : 0u), "exact qkv sliced and o/FFN down/up graph count");
                    check(lora->applied_lora_tensors.size() == lora_count && lora->skipped_incompatible_lora_tensors.empty(),
                          "actual LoRA method selected every applicable metadata tensor without skip");
                    // A non-MOSS caller retains the global Linear default even
                    // in the build where the MOSS-only compile policy is enabled.
                    Linear ordinary(256, 256, false); ordinary.init(params, {}, "non_moss_control");
                    auto* x = ggml_new_tensor_2d(context, GGML_TYPE_F32, 256, 9);
                    auto* ordinary_out = ordinary.forward(&runner, x);
                    check(ordinary_out->op == GGML_OP_MUL_MAT && ordinary_out->op_params[0] == GGML_PREC_DEFAULT,
                          "non-MOSS Linear default is not globally changed");
                    cases.push_back({{"latent_side", latent_side}, {"tokens", tokens}, {"skip_layer22", skip_one_layer},
                        {"LoRA_metadata", lora_enabled}, {"base_matmuls", base_count}, {"lora_matmuls", lora_count},
                        {"Q4_K_base", quantized}, {"BF16_base", bf16}, {"flash_nodes", flash},
                        {"accumulation", expected == GGML_PREC_F32 ? "f32" : "default"}, {"nodes", ggml_graph_n_nodes(graph)}});
                }
                ggml_free(context); ggml_free(params);
            }
        }
    }
    std::cout << nlohmann::json({{"checks", checks}, {"cases", cases}, {"parameter_dtypes", parameter_dtypes}, {"actual_MOSS_model_forward", true},
        {"exact_LoRA_method_bodies", true}, {"tensor_payloads_allocated", false}, {"graph_executed", false},
        {"backend_initialized", false}, {"model_files_opened", 0}, {"PS5_connections", 0}}).dump(2) << "\n";
}
