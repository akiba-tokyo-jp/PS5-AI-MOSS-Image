static unsigned checks;
static void check(bool ok, const char* message) {
    ++checks;
    if (!ok) { std::fprintf(stderr, "FAIL %s\n", message); std::exit(1); }
}

// These are capability-only sentinels. All tensor-data operations trap.
extern "C" bool ggml_backend_supports_op(ggml_backend_t backend, const ggml_tensor* t) {
    check(backend == reinterpret_cast<ggml_backend_t>(uintptr_t(1)), "metadata backend sentinel");
    return t->op == GGML_OP_ROPE_APPLY || t->op == GGML_OP_FLASH_ATTN_EXT;
}
